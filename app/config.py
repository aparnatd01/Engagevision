"""
Application Configuration — EngageVision
Loads all settings from environment variables (.env file).
"""

import os
from dotenv import load_dotenv

# Load .env file from the project root
load_dotenv()


class Config:
    # ── Secret Key ──────────────────────────────────────────────────────────────
    SECRET_KEY = os.environ.get('SECRET_KEY', 'engagevision-change-in-production-2024')

    # ── MySQL Database ───────────────────────────────────────────────────────────
    MYSQL_HOST     = os.environ.get('MYSQL_HOST',     'localhost')
    MYSQL_PORT     = int(os.environ.get('MYSQL_PORT', 3306))
    MYSQL_USER     = os.environ.get('MYSQL_USER',     'root')
    MYSQL_PASSWORD = os.environ.get('MYSQL_PASSWORD', '')
    MYSQL_DB       = os.environ.get('MYSQL_DB',       'engagevision')

    # ── File Uploads (for future AI sprints) ────────────────────────────────────
    BASE_DIR            = os.path.abspath(os.path.dirname(__file__))
    UPLOAD_FOLDER       = os.path.join(BASE_DIR, 'static', 'uploads', 'videos')
    CROPS_FOLDER        = os.path.join(BASE_DIR, 'static', 'uploads', 'crops')
    REPORTS_FOLDER      = os.path.join(BASE_DIR, 'static', 'uploads', 'reports')
    ALLOWED_EXTENSIONS  = {'mp4', 'avi', 'mov', 'mkv', 'webm'}
    MAX_CONTENT_LENGTH  = 500 * 1024 * 1024  # 500 MB

    # ── Session Security ─────────────────────────────────────────────────────────
    SESSION_COOKIE_HTTPONLY = True
    SESSION_COOKIE_SAMESITE = 'Lax'
    PERMANENT_SESSION_LIFETIME = 28800  # 8 hours

    # ── Email / SMTP Configuration ───────────────────────────────────────────────
    # Configure in .env — never hardcode credentials here.
    MAIL_SERVER         = os.environ.get('MAIL_SERVER',         'smtp.gmail.com')
    MAIL_PORT           = int(os.environ.get('MAIL_PORT',       587))
    MAIL_USE_TLS        = os.environ.get('MAIL_USE_TLS',        'true').lower() in ('true', '1', 'yes')
    MAIL_USE_SSL        = os.environ.get('MAIL_USE_SSL',        'false').lower() in ('true', '1', 'yes')
    MAIL_USERNAME       = os.environ.get('MAIL_USERNAME',       '')
    MAIL_PASSWORD       = os.environ.get('MAIL_PASSWORD',       '')
    MAIL_DEFAULT_SENDER = os.environ.get('MAIL_DEFAULT_SENDER', 'noreply@engagevision.edu')

    # ── AI / Engagement Model ────────────────────────────────────────────────────
    # Path to trained MobileNetV2 engagement model (generated by cv_engine.train)
    PROJECT_ROOT = os.path.abspath(os.path.join(BASE_DIR, '..'))
    ENGAGEMENT_MODEL_PATH = os.environ.get(
        'ENGAGEMENT_MODEL_PATH',
        os.path.join(PROJECT_ROOT, 'cv_engine', 'models', 'engagement_model.h5')
    )


class DevelopmentConfig(Config):
    DEBUG = True


class ProductionConfig(Config):
    DEBUG = False


config = {
    'development': DevelopmentConfig,
    'production':  ProductionConfig,
    'default':     DevelopmentConfig,
}
